// Спрощена транслітерація кирилиці латиницею (українська + поширені
// російські літери) — на основі офіційної української транслітераційної
// таблиці (постанова КМУ №55), без позиційних виключень (і/ї/є/ю/я на
// початку слова тощо), яких для MVP достатньо.
//
// ВАЖЛИВО: функція ідемпотентна — літери, які вже латиниця, цифри,
// пробіли та розділові знаки лишаються без змін. Тож її безпечноƒ
// застосовувати навіть якщо користувач уже ввів текст латиницею.

const MAP = {
  а: 'a', б: 'b', в: 'v', г: 'h', ґ: 'g', д: 'd', е: 'e', є: 'ie',
  ж: 'zh', з: 'z', и: 'y', і: 'i', ї: 'i', й: 'i', к: 'k', л: 'l',
  м: 'm', н: 'n', о: 'o', п: 'p', р: 'r', с: 's', т: 't', у: 'u',
  ф: 'f', х: 'kh', ц: 'ts', ч: 'ch', ш: 'sh', щ: 'shch', ь: '',
  ю: 'iu', я: 'ia', "'": '', '’': '',
  // поширені російські літери, яких немає в українському алфавіті
  ы: 'y', э: 'e', ё: 'e', ъ: ''
};

function transliterateChar(ch) {
  const lower = ch.toLowerCase();
  const mapped = MAP[lower];
  if (mapped === undefined) return ch; // не кирилиця — лишаємо як є
  if (ch === lower) return mapped;
  // символ був у верхньому регістрі — капіталізуємо перший символ заміни
  return mapped.charAt(0).toUpperCase() + mapped.slice(1);
}

export function transliterate(text) {
  if (!text) return '';
  return text.split('').map(transliterateChar).join('');
}

// Ім'я/прізвище завжди з великої літери в резюме, незалежно від того,
// як людина набрала текст (весь рядок малими літерами — звичайна
// ситуація при швидкому наборі на телефоні). Розбиваємо по пробілах
// і дефісах, щоб коректно капіталізувати складені прізвища
// (наприклад "ковальська-петренко" -> "Kovalska-Petrenko").
export function capitalizeWords(text) {
  if (!text) return '';
  return text.replace(/[^\s-]+/g, (word) => word.charAt(0).toUpperCase() + word.slice(1).toLowerCase());
}
